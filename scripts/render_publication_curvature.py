#!/usr/bin/env python3
"""Render the saved IBM01 endpoint-curvature diagnostic without recomputation."""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / "writeup/data/publication/curvature_diagnostics_ibm01.json"
DEFAULT_FOLLOWUP = ROOT / "writeup/data/publication/curvature_followup_ibm01.json"
DEFAULT_OUTPUT = ROOT / "writeup/latex/generated/curvature_diagnostics.tex"


def num(value: Any) -> str:
    number = float(value)
    if not math.isfinite(number):
        raise ValueError("cannot render a non-finite number")
    return r"\num{%s}" % format(number, ".2e")


def render_followup(report: dict[str, Any]) -> str:
    guarded = sorted(
        (run for run in report["runs"]
         if run["mask_name"] == "guarded_interior" and run["dtype"] == "torch.float64"),
        key=lambda run: run["seed"],
    )
    wirelength = sorted(
        (run for run in report["weighted_component_runs"]
         if run["mask_name"] == "guarded_interior" and run["component"] == "wirelength"),
        key=lambda run: run["seed"],
    )
    if len(guarded) != 2 or len(wirelength) != 2:
        raise ValueError("expected two guarded float64 directions and wirelength probes")
    for run in guarded:
        if set(run["forward_float_operation_output_counts"]) != {"torch.float64"}:
            raise ValueError("follow-up does not establish float64 forward arithmetic")
        for scale in run["scales"]:
            for comparison in ("plus_minus_branch_delta", "base_plus_branch_delta", "base_minus_branch_delta"):
                if scale[comparison]["canvas_clamp:changed_comparisons"] != 0:
                    raise ValueError("guarded follow-up contains a canvas branch change")
    jumps = [next(scale for scale in run["scales"] if scale["epsilon_microns"] == 1e-3)
             for run in guarded]
    wire = [next(scale for scale in run["scales"] if scale["epsilon_microns"] == 1e-5)
            for run in wirelength]
    return (
        r"\paragraph{Precision and branch follow-up.} "
        "A separate saved probe restricts both original directions to %d coordinates "
        r"with canvas clearance exceeding $0.1\,\mu$m in both precisions. "
        % guarded[0]["effective_coordinate_count"]
        + "All floating forward operations use float64; stored float32 constants are promoted, "
        "so recomputed bounds can shift slightly. Operation traces record no canvas-branch "
        "changes throughout the tested range. With $P$ selecting these coordinates, "
        r"the comparison uses $PH_{\mathrm{AD}}Pv$ and differences of $Pg_{\mathrm{AD}}$. "
        r"At $\epsilon=10^{-3}\,\mu$m, projected gradient-jump norms remain $%s$ and $%s$ "
        r"in $\mu\mathrm{m}^{-1}$, with relative HVP errors %.2f and %.2f. "
        % (num(jumps[0]["gradient_jump_l2_effective"]), num(jumps[1]["gradient_jump_l2_effective"]),
           jumps[0]["hvp_relative_error_effective"], jumps[1]["hvp_relative_error_effective"])
        + "An exploratory decomposition using the frozen weighted primitives localizes the "
        "remaining jumps to rectangle-grid density and RUDY terms. Guarded wirelength has "
        r"no recorded branch changes and HVP relative errors $%s$ and $%s$ at "
        r"$\epsilon=10^{-5}\,\mu$m. Thus canvas restriction and higher precision alone "
        "do not remove the composite discrepancy. These local component checks establish "
        "neither global operator correctness nor a quality benefit from Lane B."
        % (num(wire[0]["hvp_relative_error_effective"]), num(wire[1]["hvp_relative_error_effective"]))
    )


def render(report: dict[str, Any], followup: dict[str, Any]) -> str:
    scope = report["scope"]
    if scope["benchmark"] != "ibm01":
        raise ValueError("expected the saved IBM01 diagnostic")
    directions = report["random_directions"]
    if len(directions) != 2 or any(len(item["scales"]) != 5 for item in directions):
        raise ValueError("expected two directions and five scales per direction")

    baseline = report["baseline"]
    lanczos = report["bounded_lanczos"]
    relative_errors = [
        scale["hvp_vector_relative_error_l2"]
        for direction in directions for scale in direction["scales"]
    ]
    cosines = [
        scale["hvp_vector_cosine"]
        for direction in directions for scale in direction["scales"]
    ]
    lines = [
        "% Generated by scripts/render_publication_curvature.py from saved JSON; do not edit.",
        r"\subsection{Endpoint curvature diagnostic}",
        r"\label{sec:curvature-diagnostic}",
        "The frozen legacy E74 proxy at its saved final IBM01 endpoint has "
        + r"$J_B=\num{%0.5f}$ and $\lVert\nabla J_B\rVert_2=%s$. "
        % (baseline["smooth_proxy_value"], num(baseline["movable_gradient_l2_norm"]))
        + "A %d-HVP capped Lanczos probe gave Rayleigh quotient $%s$ and active-branch residual norm $%s$ using the same automatic-differentiation operator. "
        % (lanczos["hvp_count"], num(lanczos["validated_rayleigh_quotient"]), num(lanczos["validated_residual_l2"]))
        + "The quotient and residual describe the computed operator; they do not independently validate it or establish a constrained stationary saddle.",
        "",
        r"Let $x$ be the saved coordinate vector, $g_{\mathrm{AD}}(x)$ its computed gradient, and $H_{\mathrm{AD}}v$ the computed Hessian-vector product (HVP) for a movable-coordinate unit vector $v$. The central differences are",
        r"\[d_{\mathrm{FD}}(\epsilon)=\frac{J_B(x+\epsilon v)-J_B(x-\epsilon v)}{2\epsilon},\qquad"
        r" k_{\mathrm{FD}}(\epsilon)=v^{\mathsf T}\frac{g_{\mathrm{AD}}(x+\epsilon v)-g_{\mathrm{AD}}(x-\epsilon v)}{2\epsilon}.\]",
        r"Here positions and $\epsilon$ are in micrometres, so the directional-gradient and curvature columns have units $\mu\mathrm{m}^{-1}$ and $\mu\mathrm{m}^{-2}$, respectively; the proxy itself is dimensionless.",
        "",
        r"\begin{table}[htbp]",
        r"\centering\footnotesize",
        r"\caption{Central differences along two seeded random unit directions at the saved IBM01 endpoint. These are separate from the Lanczos vector with a negative Rayleigh quotient.}",
        r"\label{tab:ibm01-curvature-diagnostic}",
        r"\begin{tabular}{@{}rrrrrr@{}}",
        r"\toprule",
        r"Dir. & $\epsilon$ ($\mu$m) & \shortstack{$g_{\mathrm{AD}}^{\mathsf T}v$\\($\mu$m$^{-1}$)} & \shortstack{$d_{\mathrm{FD}}$\\($\mu$m$^{-1}$)} & \shortstack{$v^{\mathsf T}H_{\mathrm{AD}}v$\\($\mu$m$^{-2}$)} & \shortstack{$k_{\mathrm{FD}}$\\($\mu$m$^{-2}$)} \\",
        r"\midrule",
    ]
    for direction_index, direction in enumerate(directions, start=1):
        for scale in direction["scales"]:
            lines.append(
                "%d & %s & %s & %s & %s & %s \\\\"
                % (
                    direction_index,
                    num(scale["epsilon_microns_l2"]),
                    num(direction["autodiff_directional_gradient"]),
                    num(scale["cost_central_first_derivative"]),
                    num(direction["autodiff_directional_curvature_vHv"]),
                    num(scale["directional_curvature_from_gradient_fd"]),
                )
            )
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
        r"For the full-vector comparison, let $h_{\mathrm{FD}}=[g_{\mathrm{AD}}(x+\epsilon v)-g_{\mathrm{AD}}(x-\epsilon v)]/(2\epsilon)$. The reported relative error is $\lVert h_{\mathrm{FD}}-H_{\mathrm{AD}}v\rVert_2/\lVert H_{\mathrm{AD}}v\rVert_2$, and the cosine is the normalized inner product of those vectors. Across the ten rows, relative errors range from %.2f to %.0f and cosines from %s to %s. The endpoint has %d coordinates at or beyond canvas clamps. For direction~1 at $\epsilon=10^{-3}\,\mu$m, forward and backward cost slopes are $%s$ and $%s$ in $\mu\mathrm{m}^{-1}$; the sampled sides cross piecewise branches."
        % (min(relative_errors), max(relative_errors), num(min(cosines)), num(max(cosines)),
           sum(report["state"]["baseline_clamp_counts"].values()),
           num((directions[0]["scales"][0]["cost_plus"] - directions[0]["scales"][0]["cost_base"]) / directions[0]["scales"][0]["epsilon_microns_l2"]),
           num((directions[0]["scales"][0]["cost_base"] - directions[0]["scales"][0]["cost_minus"]) / directions[0]["scales"][0]["epsilon_microns_l2"])),
        "",
        "% Follow-up source: writeup/data/publication/curvature_followup_ibm01.json.",
        render_followup(followup),
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--followup-input", type=Path, default=DEFAULT_FOLLOWUP)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    report = json.loads(args.input.read_text(encoding="utf-8"))
    followup = json.loads(args.followup_input.read_text(encoding="utf-8"))
    output = render(report, followup)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output, encoding="utf-8")
    print("Rendered %s from %s and %s." % (args.output, args.input, args.followup_input))


if __name__ == "__main__":
    main()
