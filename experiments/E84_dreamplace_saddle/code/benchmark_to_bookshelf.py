"""E84: convert macro_place.Benchmark → Bookshelf format files for DREAMPlace.

Bookshelf format produces 5 files for a benchmark named <name>:
  <name>.aux    — index file pointing at the others
  <name>.nodes  — macro/cell definitions (name, width, height, [terminal])
  <name>.nets   — net connectivity (NetDegree, then per-pin lines)
  <name>.pl     — initial placement (name x y : N [/FIXED])
  <name>.scl    — row info (rows of the chip canvas)

Coordinates are scaled to integers (we use a fixed multiplier) — Bookshelf is
historically grid-aligned. DREAMPlace's loader is OK with floats but
older readers prefer ints, so we round.

Usage:
    from macro_place.bench_paths import find_benchmark_dir
    from macro_place.loader import load_benchmark_from_dir
    benchmark, _ = load_benchmark_from_dir(str(find_benchmark_dir("ibm01")))
    write_bookshelf(benchmark, out_dir="dreamplace_io/ibm01", scale=1000)
"""
from __future__ import annotations

import os
import sys
from pathlib import Path
from typing import Tuple, Union

# Make the repo root importable when this file is run directly.
_REPO_ROOT = Path(__file__).resolve().parents[3]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

import torch

from macro_place.benchmark import Benchmark


def _rint(x: Union[float, torch.Tensor], scale: int) -> int:
    """Round (x * scale) to nearest int."""
    if isinstance(x, torch.Tensor):
        x = float(x.item())
    return int(round(float(x) * scale))


def write_bookshelf(
    benchmark: Benchmark,
    out_dir: Union[str, Path],
    scale: int = 1000,
    site_width: int = 1,
    site_height: int = None,
) -> Path:
    """Write Bookshelf files for a Benchmark.

    Args:
        benchmark: macro_place.Benchmark
        out_dir: directory to write files into; created if missing
        scale: multiplier for converting microns → integer Bookshelf units
        site_width: row site width in scaled units (Bookshelf integer units)
        site_height: row height in scaled units; if None, derive from canvas
            (canvas_height / grid_rows)

    Returns:
        Path to the .aux file (the master index DREAMPlace points at).
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    name = benchmark.name

    # Derive integer canvas dimensions.
    cw = _rint(benchmark.canvas_width, scale)
    ch = _rint(benchmark.canvas_height, scale)

    # Row geometry: subdivide canvas into grid_rows rows.
    if site_height is None:
        site_height = max(1, ch // max(1, benchmark.grid_rows))

    n_total = benchmark.num_macros
    n_hard = benchmark.num_hard_macros
    n_soft = benchmark.num_soft_macros
    n_ports = int(benchmark.port_positions.shape[0])
    fixed = benchmark.macro_fixed

    # Match adaptec1's format precisely:
    #   - Use TAB separators
    #   - All fixed nodes (including IO pins) are `terminal` with non-zero dims
    #   - NumTerminals counts ALL fixed entries
    n_terminals = int(fixed.sum().item()) + n_ports

    # ── .nodes ─────────────────────────────────────────────────────────────
    # Match adaptec1's format: tabs as separators, leading tab per line,
    # all fixed nodes are `terminal` (no terminal_NI for our use case).
    # Structure: movable macros first, then terminals at the end.
    nodes_path = out_dir / f"{name}.nodes"
    movable_idxs = [i for i in range(n_total) if not bool(fixed[i])]
    terminal_idxs = [i for i in range(n_total) if bool(fixed[i])]
    with open(nodes_path, "w", newline="\n") as f:
        f.write("UCLA nodes 1.0\n")
        f.write(f"# Generated by benchmark_to_bookshelf.py for {name}\n\n")
        f.write(f"NumNodes : \t\t{n_total + n_ports}\n")
        f.write(f"NumTerminals : \t\t{n_terminals}\n")
        # Movable nodes first.
        for i in movable_idxs:
            mname = _safe_name(benchmark.macro_names[i] if i < len(benchmark.macro_names) else f"m{i}")
            w = _rint(benchmark.macro_sizes[i, 0], scale)
            h = _rint(benchmark.macro_sizes[i, 1], scale)
            if w <= 0:
                w = 1
            if h <= 0:
                h = 1
            f.write(f"\t{mname}\t{w}\t{h}\n")
        # Terminals (fixed macros) next.
        for i in terminal_idxs:
            mname = _safe_name(benchmark.macro_names[i] if i < len(benchmark.macro_names) else f"m{i}")
            w = _rint(benchmark.macro_sizes[i, 0], scale)
            h = _rint(benchmark.macro_sizes[i, 1], scale)
            if w <= 0:
                w = 1
            if h <= 0:
                h = 1
            f.write(f"\t{mname}\t{w}\t{h}\tterminal\n")
        # IO ports: tiny (1×1) terminals at fixed positions.
        for j in range(n_ports):
            f.write(f"\tport_{j}\t1\t1\tterminal\n")

    # ── .pl (initial placement) ───────────────────────────────────────────
    pl_path = out_dir / f"{name}.pl"
    with open(pl_path, "w", newline="\n") as f:
        f.write("UCLA pl 1.0\n")
        f.write(f"# Generated by benchmark_to_bookshelf.py for {name}\n\n")
        for i in range(n_total):
            mname = _safe_name(benchmark.macro_names[i] if i < len(benchmark.macro_names) else f"m{i}")
            cx = _rint(benchmark.macro_positions[i, 0], scale)
            cy = _rint(benchmark.macro_positions[i, 1], scale)
            w = _rint(benchmark.macro_sizes[i, 0], scale)
            h = _rint(benchmark.macro_sizes[i, 1], scale)
            # Bookshelf uses lower-left, our positions are centers.
            llx = cx - w // 2
            lly = cy - h // 2
            tag = " /FIXED" if bool(fixed[i]) else ""
            f.write(f"{mname}\t{llx}\t{lly}\t: N{tag}\n")
        for j in range(n_ports):
            px = _rint(benchmark.port_positions[j, 0], scale)
            py = _rint(benchmark.port_positions[j, 1], scale)
            f.write(f"port_{j}\t{px}\t{py}\t: N /FIXED\n")

    # ── .nets ─────────────────────────────────────────────────────────────
    nets_path = out_dir / f"{name}.nets"
    total_pins = sum(int(net.shape[0]) for net in benchmark.net_nodes)
    with open(nets_path, "w", newline="\n") as f:
        f.write("UCLA nets 1.0\n")
        f.write(f"# Generated by benchmark_to_bookshelf.py for {name}\n\n")
        f.write(f"NumNets : {benchmark.num_nets}\n")
        f.write(f"NumPins : {total_pins}\n\n")
        for ni, net_nodes in enumerate(benchmark.net_nodes):
            degree = int(net_nodes.shape[0])
            f.write(f"NetDegree : {degree}   n{ni}\n")
            for k in range(degree):
                node_idx = int(net_nodes[k].item())
                if node_idx < n_total:
                    mname = _safe_name(
                        benchmark.macro_names[node_idx]
                        if node_idx < len(benchmark.macro_names) else f"m{node_idx}"
                    )
                else:
                    mname = f"port_{node_idx - n_total}"
                # Pin offset 0,0 (we don't have rich pin data in Bookshelf form here).
                # First pin = driver (O), rest = sinks (I).  Matches adaptec1.
                io = "O" if k == 0 else "I"
                f.write(f"\t{mname}\t{io} : 0.000000\t0.000000\n")

    # ── .scl (row info) ───────────────────────────────────────────────────
    # Match adaptec1's format:
    #   - 2-space indent (NOT tab) for field names
    #   - Many small rows of unit height (e.g., 12 units tall on a 22900 canvas
    #     → ~1900 rows for ibm01).  This way macros span multiple rows, which
    #     is what DREAMPlace expects.
    unit_row_height = max(1, ch // 1900)  # ~1900 rows total, integer
    n_rows = ch // unit_row_height
    n_sites = cw // site_width
    scl_path = out_dir / f"{name}.scl"
    with open(scl_path, "w", newline="\n") as f:
        f.write("UCLA scl 1.0\n")
        f.write(f"# Generated by benchmark_to_bookshelf.py for {name}\n\n")
        f.write(f"NumRows : {n_rows}\n\n")
        for r in range(n_rows):
            y = r * unit_row_height
            f.write("CoreRow Horizontal\n")
            f.write(f"  Coordinate    :   {y}\n")
            f.write(f"  Height        :   {unit_row_height}\n")
            f.write(f"  Sitewidth     :    {site_width}\n")
            f.write(f"  Sitespacing   :    {site_width}\n")
            f.write("  Siteorient    :    1\n")
            f.write("  Sitesymmetry  :    1\n")
            f.write(f"  SubrowOrigin  :    0\tNumSites  :  {n_sites}\n")
            f.write("End\n")

    # ── .wts (net weights — match adaptec1 which is essentially empty) ───
    wts_path = out_dir / f"{name}.wts"
    with open(wts_path, "w", newline="\n") as f:
        f.write("UCLA wts 1.0\n")
        f.write(f"# Generated by benchmark_to_bookshelf.py for {name}\n\n")

    # ── .aux (master index) ───────────────────────────────────────────────
    aux_path = out_dir / f"{name}.aux"
    with open(aux_path, "w", newline="\n") as f:
        f.write(
            f"RowBasedPlacement :  {name}.nodes  {name}.nets  "
            f"{name}.wts  {name}.pl  {name}.scl\n"
        )

    return aux_path


def _safe_name(name: str) -> str:
    """Bookshelf node names cannot contain whitespace; replace with underscores."""
    return name.replace(" ", "_").replace("\t", "_")


def read_bookshelf_pl(pl_path: Union[str, Path], scale: int = 1000) -> dict:
    """Read a Bookshelf .pl file (DREAMPlace's output) into a name→(cx, cy) dict.

    Coordinates are scaled back to floats (microns) using `scale`.
    Bookshelf .pl gives lower-left corner; we don't return centers here
    because we don't have widths/heights in this dict — caller can shift.
    """
    out = {}
    with open(pl_path, "r") as f:
        first = f.readline()
        if not first.startswith("UCLA"):
            raise ValueError(f"{pl_path}: not a UCLA Bookshelf .pl file")
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 3:
                continue
            mname = parts[0]
            try:
                llx = int(parts[1])
                lly = int(parts[2])
            except ValueError:
                continue
            out[mname] = (llx / scale, lly / scale)
    return out


