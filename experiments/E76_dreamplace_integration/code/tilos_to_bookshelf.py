"""Convert a TILOS-protobuf benchmark to Bookshelf format for DREAMPlace.

Bookshelf format files emitted (per bench):
  <name>.nodes    — node list with width/height (and 'terminal' for fixed)
  <name>.nets     — net connectivity with pin offsets
  <name>.pl       — initial placement (fixed nodes get '/FIXED')
  <name>.scl      — row/site definition (uniform rows covering the canvas)
  <name>.wts      — net weights (all 1.0)
  <name>.aux      — manifest pointing at the above

DREAMPlace expects Bookshelf input via the `.aux` file. Once we ship the
five generated files to a cloud GPU box, DREAMPlace can ingest them
directly without further format work.

Usage:
  uv run python experiments/E76_dreamplace_integration/code/tilos_to_bookshelf.py \
      <bench_name> [<out_dir>]

  e.g.
  uv run python ... tilos_to_bookshelf.py ibm01 experiments/E76_dreamplace_integration/bookshelf_out/ibm01
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import torch

_HERE = Path(__file__).resolve().parent
_ROOT = _HERE.parents[2]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from macro_place.bench_paths import find_benchmark_dir
from macro_place.loader import load_benchmark_from_dir


# DREAMPlace's Bookshelf parser is integer-strict. We scale all positions
# and sizes by SCALE before writing, then divide by SCALE on read-back.
SCALE = 1000


def _node_name(idx: int) -> str:
    """Bookshelf node name. We use a uniform `n<idx>` scheme so the .pl/.nets
    files can reference by index without parsing the original instance names."""
    return f"n{idx}"


def _write_nodes(benchmark, out_dir: Path) -> None:
    n = benchmark.num_macros
    sizes = benchmark.macro_sizes.cpu().numpy()
    fixed = benchmark.macro_fixed.cpu().numpy()
    num_terminals = int(fixed.sum())
    num_nodes = n
    with open(out_dir / f"{benchmark.name}.nodes", "w") as f:
        f.write("UCLA nodes 1.0\n")
        f.write("# Generated by tilos_to_bookshelf.py from TILOS-protobuf benchmark\n\n")
        f.write(f"NumNodes : {num_nodes}\n")
        f.write(f"NumTerminals : {num_terminals}\n")
        for i in range(n):
            w = max(1, int(round(float(sizes[i, 0]) * SCALE)))
            h = max(1, int(round(float(sizes[i, 1]) * SCALE)))
            term = " terminal" if bool(fixed[i]) else ""
            f.write(f"  {_node_name(i)}\t{w}\t{h}{term}\n")


def _write_pl(benchmark, out_dir: Path) -> None:
    pos = benchmark.macro_positions.cpu().numpy()
    sizes = benchmark.macro_sizes.cpu().numpy()
    fixed = benchmark.macro_fixed.cpu().numpy()
    n = benchmark.num_macros
    with open(out_dir / f"{benchmark.name}.pl", "w") as f:
        f.write("UCLA pl 1.0\n")
        f.write("# Centers from TILOS protobuf; converted to lower-left for Bookshelf\n\n")
        for i in range(n):
            cx, cy = float(pos[i, 0]), float(pos[i, 1])
            w, h = float(sizes[i, 0]), float(sizes[i, 1])
            llx = int(round((cx - w / 2.0) * SCALE))
            lly = int(round((cy - h / 2.0) * SCALE))
            fixed_tag = " /FIXED" if bool(fixed[i]) else ""
            f.write(f"  {_node_name(i)}\t{llx}\t{lly} : N{fixed_tag}\n")


def _write_nets(benchmark, out_dir: Path) -> None:
    """Bookshelf nets: each net lists its pins. We use net_nodes (per-net
    macro index list); we don't have per-pin offsets exposed cleanly, so we
    write the pin at the macro center (offset 0,0). DREAMPlace's HPWL is
    bbox-based; an offset-zero approximation produces the same bounding
    boxes as long as the original benchmark's pins are inside the macro
    bbox (which they are by construction).
    """
    nets = benchmark.net_nodes
    weights = benchmark.net_weights.cpu().numpy() if hasattr(benchmark, "net_weights") else None
    num_nets = len(nets)
    num_pins = sum(int(net.numel()) for net in nets)
    with open(out_dir / f"{benchmark.name}.nets", "w") as f:
        f.write("UCLA nets 1.0\n")
        f.write("# Generated; pin offsets defaulted to (0,0) — bbox HPWL preserved\n\n")
        f.write(f"NumNets : {num_nets}\n")
        f.write(f"NumPins : {num_pins}\n\n")
        for j, net in enumerate(nets):
            nodes = net.cpu().numpy().tolist()
            w = float(weights[j]) if weights is not None else 1.0
            f.write(f"NetDegree : {len(nodes)} net{j}\n")
            for nidx in nodes:
                f.write(f"  {_node_name(int(nidx))} I : 0.000 0.000\n")


def _write_scl(benchmark, out_dir: Path) -> None:
    """Site/row definition. We treat the canvas as a uniform grid of rows
    1.0 μm tall, 1.0 μm site width — DREAMPlace doesn't strictly need
    rigorous row alignment for macro placement, but Bookshelf format
    requires this section.
    """
    cw = float(benchmark.canvas_width)
    ch = float(benchmark.canvas_height)
    row_height = 1.0
    site_width = 1.0
    num_rows = max(1, int(ch / row_height))
    # DREAMPlace Bookshelf parser is integer-strict. We use the SCALE
    # factor to map μm → integer units consistent with .nodes/.pl.
    # Row height = 100 scaled units (= 0.1 μm) — fine grain for placement.
    # Number of rows covers full canvas height.
    row_h_int = 100
    site_w_int = 100
    cw_int = int(round(cw * SCALE))
    ch_int = int(round(ch * SCALE))
    num_rows_int = max(1, ch_int // row_h_int + 1)
    num_sites_int = max(1, cw_int // site_w_int + 1)
    with open(out_dir / f"{benchmark.name}.scl", "w") as f:
        f.write("UCLA scl 1.0\n")
        f.write("# Uniform-row site definition for macro placement\n\n")
        f.write(f"NumRows : {num_rows_int}\n\n")
        for r in range(num_rows_int):
            y = r * row_h_int
            f.write("CoreRow Horizontal\n")
            f.write(f"  Coordinate    :  {y}\n")
            f.write(f"  Height        :  {row_h_int}\n")
            f.write(f"  Sitewidth     :  {site_w_int}\n")
            f.write(f"  Sitespacing   :  {site_w_int}\n")
            f.write("  Siteorient    :  N\n")
            f.write("  Sitesymmetry  :  Y\n")
            f.write(f"  SubrowOrigin  :  0\tNumSites :  {num_sites_int}\n")
            f.write("End\n")


def _write_wts(benchmark, out_dir: Path) -> None:
    nets = benchmark.net_nodes
    weights = benchmark.net_weights.cpu().numpy() if hasattr(benchmark, "net_weights") else None
    with open(out_dir / f"{benchmark.name}.wts", "w") as f:
        f.write("UCLA wts 1.0\n")
        for j, net in enumerate(nets):
            w = float(weights[j]) if weights is not None else 1.0
            f.write(f"net{j}\t{w:.6f}\n")


def _write_aux(benchmark, out_dir: Path) -> None:
    n = benchmark.name
    with open(out_dir / f"{n}.aux", "w") as f:
        f.write(f"RowBasedPlacement : {n}.nodes  {n}.nets  {n}.wts  {n}.pl  {n}.scl\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("bench")
    ap.add_argument("out_dir", nargs="?", default=None)
    args = ap.parse_args()

    bench_name = args.bench
    out_dir = Path(args.out_dir or
                   _HERE.parent / "bookshelf_out" / bench_name)
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"[bookshelf] loading {bench_name}...")
    benchmark, plc = load_benchmark_from_dir(str(find_benchmark_dir(bench_name)))

    print(f"[bookshelf] writing files to {out_dir}/")
    _write_nodes(benchmark, out_dir)
    _write_pl(benchmark, out_dir)
    _write_nets(benchmark, out_dir)
    _write_scl(benchmark, out_dir)
    _write_wts(benchmark, out_dir)
    _write_aux(benchmark, out_dir)

    print(f"[bookshelf] {bench_name} → {out_dir}/{{nodes,pl,nets,scl,wts,aux}}")
    print(f"  num_macros = {benchmark.num_macros}")
    print(f"  num_hard   = {benchmark.num_hard_macros}")
    print(f"  num_fixed  = {int(benchmark.macro_fixed.sum())}")
    print(f"  num_nets   = {benchmark.num_nets}")
    print(f"  canvas     = {benchmark.canvas_width:.2f} x {benchmark.canvas_height:.2f}")


if __name__ == "__main__":
    main()
